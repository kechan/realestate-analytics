// Regenerate the small navigation-only map from Natural Earth's public-domain
// ne_50m_admin_1_states_provinces.geojson. Pass the downloaded source as argv[2].
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const source = readFileSync(process.argv[2]);
const features = JSON.parse(source).features.filter(f => f.properties.admin === 'Canada');
if (features.length !== 13) throw new Error('Expected all 13 Canadian provinces and territories');
const rad = Math.PI / 180;
const p1 = 49 * rad, p2 = 77 * rad, origin = -96 * rad;
const n = Math.log(Math.cos(p1) / Math.cos(p2)) / Math.log(Math.tan(Math.PI / 4 + p2 / 2) / Math.tan(Math.PI / 4 + p1 / 2));
const f = Math.cos(p1) * Math.pow(Math.tan(Math.PI / 4 + p1 / 2), n) / n;
function project([lng, lat]) {
  const rho = f / Math.pow(Math.tan(Math.PI / 4 + lat * rad / 2), n);
  return [rho * Math.sin(n * (lng * rad - origin)), rho * Math.cos(n * (lng * rad - origin))];
}
const polygons = feature => feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
const all = features.flatMap(feature => polygons(feature).flat(2).map(project));
if (all.some(point => !point.every(Number.isFinite))) throw new Error('Invalid projected coordinates');
const minX = Math.min(...all.map(p => p[0])), maxX = Math.max(...all.map(p => p[0]));
const minY = Math.min(...all.map(p => p[1])), maxY = Math.max(...all.map(p => p[1]));
const scale = Math.min(940 / (maxX - minX), 650 / (maxY - minY));
const xy = point => { const [x, y] = project(point); return [+(30 + (x - minX) * scale).toFixed(1), +(25 + (y - minY) * scale).toFixed(1)]; };
const anchors = { YT: [-136, 64.5], NT: [-120, 65], NU: [-96, 68], BC: [-124, 54], AB: [-115, 55], SK: [-106, 55], MB: [-98, 55],
  ON: [-86, 50], QC: [-72, 53], NB: [-66.5, 47], NS: [-62, 44.5], PE: [-61, 47], NL: [-56.5, 53] };
const shapes = features.map(feature => {
  const code = feature.properties.iso_3166_2.slice(3);
  const rings = polygons(feature).flat(1).map(ring => ring.map(xy));
  const points = rings.flat();
  const x = Math.min(...points.map(p => p[0])), y = Math.min(...points.map(p => p[1]));
  const right = Math.max(...points.map(p => p[0])), bottom = Math.max(...points.map(p => p[1]));
  return { code, path: rings.map(ring => 'M' + ring.map(p => p.join(',')).join('L') + 'Z').join(''),
    bounds: [x, y, +(right - x).toFixed(1), +(bottom - y).toFixed(1)], label: xy(anchors[code]) };
});
const output = `// Generated by scripts/build-canada-map.mjs; do not hand-edit paths.\n// Natural Earth 1:50m Admin 1, public domain. Navigation outlines, not analytical boundaries.\n// Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_admin_1_states_provinces.geojson\n// Source SHA-256: ${createHash('sha256').update(source).digest('hex')}\nexport interface ProvinceShape { code: string; path: string; bounds: number[]; label: number[] }\nexport const CANADA_SHAPES: ProvinceShape[] = ${JSON.stringify(shapes)};\n`;
writeFileSync(fileURLToPath(new URL('../src/domain/canadaMap.ts', import.meta.url)), output);
// Geographic coordinates for the interactive provincial Leaflet map. Keep this
// separate from the national SVG chunk so neither view loads the other format.
const boundaries = Object.fromEntries(features.map(feature => [feature.properties.iso_3166_2.slice(3), {
  type: 'Feature', properties: {}, geometry: feature.geometry,
}]));
writeFileSync(fileURLToPath(new URL('../src/domain/provinceBoundaries.ts', import.meta.url)),
  `// Generated by scripts/build-canada-map.mjs. Natural Earth, public domain; navigation only.\n// Source SHA-256: ${createHash('sha256').update(source).digest('hex')}\nimport type { Feature } from 'geojson';\nimport type { GeoGeometry } from '../types';\nexport const PROVINCE_BOUNDARIES: Record<string, Feature<GeoGeometry>> = ${JSON.stringify(boundaries)};\n`);
console.log(`Prepared ${shapes.length} province/territory outlines (${Math.round(output.length / 1024)} KB)`);
